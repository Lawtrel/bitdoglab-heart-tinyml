"""Contratos estruturais para trocar runtime, áudio ou dispositivo."""
from typing import Protocol
from .models import AudioWindow, InferenceOutput, BoardCapture

class Predictor(Protocol):
    def predict(self, audio: AudioWindow) -> InferenceOutput: ...

class AudioDecoder(Protocol):
    def decode(self, blob: bytes, start: float = 0.0) -> AudioWindow: ...
    def encode(self, audio: AudioWindow) -> bytes: ...

class BoardGateway(Protocol):
    def ports(self) -> list[dict]: ...
    def connect(self, port: str = "auto") -> dict: ...
    def infer(self, audio: AudioWindow, port: str = "auto") -> dict: ...
    def capture(self, port: str = "auto") -> BoardCapture: ...
